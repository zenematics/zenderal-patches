"""Seismic Stomp with a weapon out: put Enderal's stomp clip into Hot Key Skill's custom slot J, via OAR.

Enderal's own stomp (_00E_IdleStomp, FNIS idle `Stomp` -> animations\\enderal\\stomp.hkx) is an unarmed idle; played
with a weapon drawn it left the behaviour graph unarmed while the sword stayed in hand, and no attack worked
(curator, 2026-10-22). Hot Key Skill (Nexus 86352, in the list) adds to 1hm_behavior an unconditioned wildcard
transition on the event `CustomStartJ` that plays `HKS_CustomAnimJ.hkx` and returns to the drawn weapon by itself; its
custom clips ship as meaningless placeholders meant to be replaced through DAR/OAR, and no list mod replaces slot J.
This writes an OAR submod whose HKS_CustomAnimJ.hkx is Enderal's stomp.hkx, into both Prophecy MO2 mods.
ZP_SeismicStompEffect sends CustomStartJ when a melee weapon (or fists) is out.

The clip is SureAI's, so it is copied from the install, not committed (as StaffDrawFix does with Bethesda's).
Usage: python -I src/Prophecy/tools/04-install-stomp-anim.py [<MO2 mods dir>]
"""
import os, sys, json, shutil, hashlib

MODS = ['Zenderal - Prophecy', 'Zenderal - Prophecy v2 (Sanctum)']
OAR = ['meshes', 'actors', 'character', 'animations', 'OpenAnimationReplacer', 'Zenderal - Prophecy']
SUBMOD = 'Seismic Stomp in Hot Key Skill slot J'
CLIP = 'HKS_CustomAnimJ.hkx'
SOURCE = os.path.join('meshes', 'actors', 'character', 'animations', 'enderal', 'stomp.hkx')
MOD_CONFIG = {
    'name': 'Zenderal - Prophecy',
    'author': 'Zenderal',
    'description': "Animations for The Prophecy's powers.",
}
SUBMOD_CONFIG = {
    'name': SUBMOD,
    'description': "Enderal's stomp as Hot Key Skill's custom animation J, which Seismic Stomp plays with a melee "
                   'weapon drawn (CustomStartJ). Nothing else in the list uses slot J.',
    'priority': 2100000000,
    'conditions': [],
}


def main():
    mods = sys.argv[1] if len(sys.argv) > 1 else r'E:\Zenderal\mods'
    src = os.path.join(os.path.dirname(mods.rstrip('/\\')), 'Stock Game', 'Data', SOURCE)
    assert os.path.isfile(src), f'Enderal stomp clip not found: {src}'
    blob = open(src, 'rb').read()
    for m in MODS:
        root = os.path.join(mods, m)
        assert os.path.isdir(root), f'MO2 mod folder missing: {root}'
        mod_dir = os.path.join(root, *OAR)
        sub_dir = os.path.join(mod_dir, SUBMOD)
        if os.path.isdir(sub_dir):
            shutil.rmtree(sub_dir)          # generated by this script only
        os.makedirs(sub_dir)
        with open(os.path.join(mod_dir, 'config.json'), 'w', encoding='utf-8') as fh:
            json.dump(MOD_CONFIG, fh, indent=4)
        with open(os.path.join(sub_dir, 'config.json'), 'w', encoding='utf-8') as fh:
            json.dump(SUBMOD_CONFIG, fh, indent=4)
        with open(os.path.join(sub_dir, CLIP), 'wb') as fh:
            fh.write(blob)
        print(f'{len(blob):>8}  {hashlib.sha1(blob).hexdigest()[:12]}  {CLIP} <- stomp.hkx  ->  {sub_dir}')


if __name__ == '__main__':
    main()
