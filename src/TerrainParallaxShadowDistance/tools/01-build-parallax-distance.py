"""Build the MO2 mod `Zenderal - Terrain Parallax Shadow Distance`: Bottled Shaders' terrain parallax reaches further.

Bottled Shaders (Nexus 192816, 1.0.22) limits terrain parallax by view depth, all hard-coded (no setting):

  1. Shadows: `Lighting.hlsl` sets `hasTerrainParallaxShadow = viewPosition.z < ExtendedMaterials::ParallaxCheapDistance
     && ...`; `ParallaxCheapDistance` is `static const float 1024.0` in `ExtendedMaterials/ExtendedMaterials.hlsli`.
     A hard cut: past ~15 m the cobbles lose their crevice shadows at once (a line that moves with the player).
  2. Depth: `ExtendedMaterialsParallaxCore.hlsli` fades the displacement to flat over
     `smoothstep(1024.0 * 1024.0, 2048.0 * 2048.0, distance * distance)` (`nearBlendToFar`).
  3. Cut-off: `Lighting.hlsl` skips terrain parallax entirely past `viewPosition.z < 2048.0` (`doTerrainPom`).

This copies the three installed files verbatim with only those numbers scaled by FACTOR (default 2: shadows 2048,
depth fade 2048-4096, cut-off 4096), each replacement asserted to hit exactly once, into the MO2 mod, which must
OUTRANK Bottled Shaders (below it in MO2's left pane). The output is Bottled Shaders' own source and is not committed.
Community Shaders recompiles shaders when their source changes; if nothing moves, clear the shader cache in its menu
and restart.

Usage: python 01-build-parallax-distance.py [<factor>] [<MO2 root>]     (defaults 2, E:/Zenderal)
"""
import os
import sys

FACTOR = float(sys.argv[1]) if len(sys.argv) > 1 else 2.0
MO2 = sys.argv[2] if len(sys.argv) > 2 else "E:/Zenderal"
SRC_MOD = os.path.join(MO2, "mods", "Bottled Shaders")
OUT_MOD = os.path.join(MO2, "mods", "Zenderal - Terrain Parallax Shadow Distance")


def f(v):
    return b"%.1f" % (v * FACTOR)


EDITS = {
    os.path.join("Shaders", "ExtendedMaterials", "ExtendedMaterials.hlsli"): [
        (b"static const float ParallaxCheapDistance = 1024.0;",
         b"static const float ParallaxCheapDistance = " + f(1024) + b";"),
    ],
    os.path.join("Shaders", "ExtendedMaterials", "ExtendedMaterialsParallaxCore.hlsli"): [
        (b"smoothstep(1024.0 * 1024.0, 2048.0 * 2048.0, distance * distance)",
         b"smoothstep(" + f(1024) + b" * " + f(1024) + b", " + f(2048) + b" * " + f(2048) + b", distance * distance)"),
    ],
    os.path.join("Shaders", "Lighting.hlsl"): [
        (b"const bool doTerrainPom = viewPosition.z < 2048.0 && terrainHasDisplacement;",
         b"const bool doTerrainPom = viewPosition.z < " + f(2048) + b" && terrainHasDisplacement;"),
    ],
}

for rel, edits in EDITS.items():
    raw = open(os.path.join(SRC_MOD, rel), "rb").read()
    for old, new in edits:
        n = raw.count(old)
        if n != 1:
            raise SystemExit("%s: expected 1 of %r, found %d (Bottled Shaders changed - re-read it)" % (rel, old, n))
        raw = raw.replace(old, new)
        print("%s: %s" % (rel, new.decode()))
    dst = os.path.join(OUT_MOD, rel)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    open(dst, "wb").write(raw)
with open(os.path.join(OUT_MOD, "meta.ini"), "w", encoding="utf-8", newline="\r\n") as fh:
    fh.write("[General]\ngameName=EnderalSE\nmodid=0\nversion=1.1.0\n"
             "comments=Generated by zenderal-patches src/TerrainParallaxShadowDistance/tools/01 from Bottled Shaders. "
             "Must outrank Bottled Shaders (below it in MO2's left pane).\n")
