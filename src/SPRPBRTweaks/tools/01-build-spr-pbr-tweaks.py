"""Build `Zenderal - SPR PBR Tweaks`: lower PGPatcher's PBR displacement for SPR PBR's Duenenhaim (desert town) set.

Enderal Retexture Project - PBR Conversion (Enderal Nexus 1063) gives every texture `displacement_scale` 1. Its
Duenenhaim height maps are SRP's own 2022 `_p` files: mostly flat with dark speckle, which CS PBR parallax at full
strength drags into fur-like streaks (Old Ishmorlep tower `_00E_SandOldCityTower02 0607D1`, loamwall01,
reported 2026-10-24 with video). This copies each of those PBRNifPatcher JSONs to the same path in its own MO2 mod,
with only `displacement_scale` changed, so SPR PBR's files stay untouched and PGPatcher reads the override.

Usage:  python 01-build-spr-pbr-tweaks.py [<MO2 root>] [--scale S] [--dry-run]     (default E:/Zenderal, 0.3)
"""
import json
import os
import sys

args = [a for a in sys.argv[1:] if not a.startswith('--')]
MO2 = args[0] if args else 'E:/Zenderal'
DRY = '--dry-run' in sys.argv
SCALE = float(sys.argv[sys.argv.index('--scale') + 1]) if '--scale' in sys.argv else 0.3

MOD = 'Zenderal - SPR PBR Tweaks'
SRC_MOD = 'SPR PBR - Architecture Dungeons Misc'
DIRS = (os.path.join('PBRNifPatcher', 'enderal', 'architecture', 'duenenhaim'),)
# No PBR parallax at all: 0.3 still streaked on the Old Ishmorlep tower (video 2026-10-24 23:56). That tower is
# Skyrim's Markarth dwarf tower; two of its loamwall01 shapes have ~14% of their area stretched > 3x by the UVs,
# which displacement turns into smeared streaks. PBR shading (roughness/normal) is kept.
FLAT = {'loamwall01.json', 'loamwall02.json'}


def main():
    n = 0
    for d in DIRS:
        src_dir = os.path.join(MO2, 'mods', SRC_MOD, d)
        assert os.path.isdir(src_dir), src_dir
        for f in sorted(os.listdir(src_dir)):
            if not f.lower().endswith('.json'):
                continue
            entries = json.load(open(os.path.join(src_dir, f), encoding='utf-8'))
            assert isinstance(entries, list) and entries, f
            flat = f.lower() in FLAT
            for e in entries:
                assert 'displacement_scale' in e and 'parallax' in e, (f, e)
                old = e['displacement_scale']
                e['displacement_scale'] = 0.0 if flat else SCALE
                if flat:
                    e['parallax'] = False
            what = 'parallax off' if flat else f'displacement {old:g} -> {SCALE:g}'
            print(f'  {f}: {what} ({len(entries)} entr{"y" if len(entries) == 1 else "ies"})')
            n += 1
            if not DRY:
                dst = os.path.join(MO2, 'mods', MOD, d, f)
                os.makedirs(os.path.dirname(dst), exist_ok=True)
                with open(dst, 'w', encoding='utf-8') as out:
                    json.dump(entries, out, indent=4)
    assert n, 'no JSONs found'
    if not DRY:
        with open(os.path.join(MO2, 'mods', MOD, 'meta.ini'), 'w', encoding='utf-8', newline='\r\n') as f:
            f.write('[General]\ngameName=EnderalSE\nmodid=0\nversion=1.0.0\n'
                    'comments=Generated by zenderal-patches src/SPRPBRTweaks/tools/01. Sort ABOVE SPR PBR; rerun PGPatcher.\n')
    print(f'{MOD}: {n} JSONs{" (dry run)" if DRY else ""}')


if __name__ == '__main__':
    main()
