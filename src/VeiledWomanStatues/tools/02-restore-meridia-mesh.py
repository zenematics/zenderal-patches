"""Build the MO2 mod `Zenderal - Veiled Woman Statue`: Enderal's own Statue of Meridia mesh back.

Mandragorasprouts' Statues for Enderal ships its own sculpt loose at `meshes\\clutter\\statues\\statueofmeridia01.nif`,
the mesh of base `LoadScreenStatueofMeridia01 10A17A`, which Enderal uses for the Veiled Woman (7 placements,
6 of which tools/01 restores; the 7th is in DGraeberpfadeL1). This writes base Enderal's copy, read from
`Skyrim - Meshes0.bsa` (the only other provider in the list, checked 2026-11-08), into an MO2 mod that must OUTRANK
the statue mod (above it in modlist.txt / below it in MO2's left pane). Textures are untouched. Enderal's asset,
so nothing here is committed but this script.

Usage: python 02-restore-meridia-mesh.py [<MO2 root>]
"""
import importlib.util
import os
import sys

MO2 = sys.argv[1] if len(sys.argv) > 1 else "E:/Zenderal"
PATH = "meshes/clutter/statues/statueofmeridia01.nif"
OUT_MOD = os.path.join(MO2, "mods", "Zenderal - Veiled Woman Statue")
HERE = os.path.dirname(os.path.abspath(__file__))

argv, sys.argv = sys.argv, [sys.argv[0]]  # the BSA helper's module reads argv at import
spec = importlib.util.spec_from_file_location(
    "al", os.path.join(HERE, "..", "..", "AspectLayout", "tools", "01-build-layout-sets.py"))
al = importlib.util.module_from_spec(spec)
spec.loader.exec_module(al)
sys.argv = argv

entry = al.bsa_index(os.path.join(MO2, "Stock game", "Data", "Skyrim - Meshes0.bsa")).get(PATH)
if not entry:
    sys.exit(f"{PATH} not in Skyrim - Meshes0.bsa")
data = al.bsa_read(entry)
assert data[:20].startswith(b"Gamebryo File Format"), "not a NIF"
dst = os.path.join(OUT_MOD, *PATH.split("/"))
os.makedirs(os.path.dirname(dst), exist_ok=True)
open(dst, "wb").write(data)
with open(os.path.join(OUT_MOD, "meta.ini"), "w", encoding="utf-8", newline="\r\n") as f:
    f.write("[General]\ngameName=EnderalSE\nmodid=0\nversion=1.0.0\n"
            "comments=Generated by zenderal-patches src/VeiledWomanStatues/tools/02: Enderal's own Statue of Meridia "
            "(the Veiled Woman). Must outrank Mandragorasprouts' Statues for Enderal.\n")
print(f"{len(data)} bytes -> {dst}")
