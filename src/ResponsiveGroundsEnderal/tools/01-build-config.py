"""Responsive Grounds on Enderal: write the settings file that tells it which of Enderal's ground textures kick up what.

Responsive Grounds (W1terr, Nexus SSE 197435, GPL-3.0) picks what the land kicks up from the diffuse FILE NAME of the
landscape texture painted there (`src/Terrain.cpp` `DefaultStrength`): "fallforest" -> autumn leaves, "pineforest" ->
green leaves, "dirt"/"mud" -> dust, "rock"/"gravel" -> pebbles, "snow" -> snow. Those are Skyrim's names. In Enderal
they still fit where Enderal kept Skyrim's files (fallforest = Goldenforst, pineforest = the northern Heartland pine
forests, snow = Northwind Mountains), but Enderal's own sand, desert, beach, path and desert-rock textures match no
rule and kick up nothing.

The mod reads per-texture choices from `Data/SKSE/Plugins/ResponsiveGrounds.json` (`src/Settings.cpp`): for each kind
("leaves", "greenLeaves", "dust", "rocks", "snow") a "textures" object keyed by the lower-case file name, each
{"enabled": bool, "strength": 0..1}. Textures without an entry keep their default; every other setting keeps its
default when the key is absent. This writes only the entries that differ from the mod's own default.

Where each texture is painted comes from the land layers of every exterior cell in reference/base (Skyrim.esm with
EnderalFS's land on top), per texture file, with the nearest map markers (2026-11-09 survey; see
arch-docs/patches/ResponsiveGroundsEnderal.md). Textures painted nowhere on land are left alone.

Writes (UTF-8, LF):
  src/ResponsiveGroundsEnderal/SKSE/Plugins/ResponsiveGrounds.json          (committed, shipped by build/manifest.json)
  <MO2>/mods/Zenderal - Responsive Grounds Enderal/SKSE/Plugins/ResponsiveGrounds.json  (+ meta.ini)

Usage: python -I src/ResponsiveGroundsEnderal/tools/01-build-config.py [<MO2 instance dir>]
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PATCH = os.path.dirname(HERE)
REPO = os.path.dirname(os.path.dirname(PATCH))
REF = os.path.join(REPO, 'reference')
MOD = 'Zenderal - Responsive Grounds Enderal'
KINDS = ['leaves', 'greenLeaves', 'dust', 'rocks', 'snow']   # the mod's JSON keys, Settings.cpp kKeys
META = ('[General]\r\ngameName=EnderalSE\r\nmodid=0\r\nversion=1.0.0\r\n'
        'comments=Generated by zenderal-patches src/ResponsiveGroundsEnderal/tools/01: Responsive Grounds\' '
        'per-texture settings for Enderal\'s ground (desert sand, beaches, paths, desert rock). '
        'Sort directly above Responsive Grounds.\r\n')

# file name -> {kind: strength}; 0 = take a default out. Shares of the mod's full amount, on its own scale: its
# defaults are dirt 0.8, mud 0.6, rock 0.75, gravel 0.8, its Sand object material 0.7, Whiterun stone road 0.15,
# stone road 0.2 dust / 0.25 rocks, winter road 0.25 dust / 0.5 snow (Terrain.cpp kRoadKinds).
MAPPING = {
    # Powder Desert (Duneville, Old Yogosh, Old Ishmartep, The Hollow Hand): dry sand, the Sand material's 0.7.
    # desertdunes.dds is also _00E_Tropical_DustGravel.
    'desertdunes.dds':   {'dust': 0.7},
    'desertdunes02.dds': {'dust': 0.7},
    'desertdunes03.dds': {'dust': 0.7},
    '(hyperactivexchild)sand_beach_01.dds': {'dust': 0.5},   # _00E_DesertDunes / _00E_WhiteSandyBeach
    # The coasts and shallows (Fogville harbour, lighthouses, Old Sherath; the mod kicks nothing up under water):
    # wet sand, less than dry.
    'ground_wet_sand01_dxt1.dds': {'dust': 0.4},
    'ground_wet_sand02_dxt1.dds': {'dust': 0.4},
    # Desert coast (The Hollow Hand, Duneville, Powder Cliff) and Qyra Island.
    'tropicalbeach01.dds': {'dust': 0.5},
    'tropicalbeach02.dds': {'dust': 0.5},
    # Goldenforst coast (Wellwatch, Old Guard Post) and Northwind shore: Skyrim's pebbly beach.
    'coastbeach01.dds': {'dust': 0.3, 'rocks': 0.3},
    'coastbeach02.dds': {'dust': 0.3, 'rocks': 0.3},
    # Dry ground: _00E_Tropical_DustFloor (Goldenforst, desert), _00E_Tropical_DryGrass (Old Darkesh),
    # LCaveDirt (the pirate hideout's worldspace).
    'tropicalfloor.dds':    {'dust': 0.7},
    'dryground01.dds':      {'dust': 0.7},
    'cavebaseground01.dds': {'dust': 0.6},
    # Tropical forest floor (Qyra Island, the Duneville oasis): leaf litter.
    'tropicalforestfloor.dds':   {'greenLeaves': 0.6, 'dust': 0.2},
    'tropicalforestfloor02.dds': {'greenLeaves': 0.6, 'dust': 0.2},
    # Desert rock (_00E_Tropical_Rocks01LT: Duneville, Qyra Island), river-bed gravel (Riverville, Wellwatch).
    'mountainslab01desert.dds': {'rocks': 0.6},
    'riverbededge.dds':         {'rocks': 0.5},
    # Paved roads: Ark's and Riverville's cobbles, the stone paths. Whiterun stone's 0.15 dust.
    'cobblestone02.dds':     {'dust': 0.15},
    'stonepath.dds':         {'dust': 0.15},
    'tropicalstonepath.dds': {'dust': 0.2, 'rocks': 0.25},
    # Rock paths (Wellwatch, Eastern Cannon-Wall): a path, not a scree field; the mod's stone road values
    # instead of its 0.75 rock default.
    'rockpath_dxt1.dds':   {'dust': 0.2, 'rocks': 0.25},
    'rockpath02_dxt1.dds': {'dust': 0.2, 'rocks': 0.25},
    # The iced rock path of the Northwind Mountains (Northwind Camp, Excavation Site): snow, not pebbles.
    'rockpathiced_dxt1.dds': {'rocks': 0, 'snow': 0.4},
    # LCaveGroundSnow: the Crystal Temple entrance's snowy cave floor.
    'cavebaseground02.dds': {'snow': 0.5},
}


# ---- the mod's own defaults (Terrain.cpp DefaultStrength, Responsive Grounds 3.0), to write only real changes

def default_strength(kind, name):
    n = name.lower()
    if kind == 'leaves':
        if 'fallforest' not in n or 'road' in n: return 0.0
        if 'leaves' in n or 'leaf' in n: return 1.0
        if 'grass' in n: return 0.6
        if 'dirt' in n: return 0.5
        if 'rock' in n: return 0.35
        return 0.6
    if kind == 'greenLeaves':
        if 'pineforest' not in n or 'road' in n: return 0.0
        if 'pineforest02' in n: return 1.0
        if 'pineforest03' in n: return 0.5
        return 0.6
    if kind == 'dust':
        if ('dirt' not in n and 'mud' not in n) or 'snow' in n: return 0.0
        if 'fallforest' in n: return 0.3
        if 'mud' in n: return 0.6
        return 0.8
    if kind == 'rocks':
        if ('rock' not in n and 'gravel' not in n) or 'snow' in n: return 0.0
        if 'gravel' in n: return 0.8
        if 'fallforest' in n: return 0.4
        if 'moss' in n: return 0.5
        if 'tundra' in n and 'volcanic' not in n: return 0.6
        if 'ash' in n: return 0.6
        return 0.75
    if kind == 'snow':
        if 'snow' not in n: return 0.0
        if 'stone' in n or 'cobble' in n: return 0.3
        if 'rock' in n: return 0.5
        if 'grass' in n: return 0.6
        if 'path' in n or 'dirt' in n: return 0.7
        return 1.0
    raise KeyError(kind)


# ---- Enderal's landscape texture files

def rd(p):
    return open(p, encoding='utf-8', errors='replace').read()


def file_name(path):
    return re.split(r'[\\/]', path)[-1].lower() if path else ''


def landscape_files():
    """{file name: [LTEX EditorIDs]} from reference/base (Skyrim.esm's LTEX, FS's texture sets over Skyrim's), and
    {texture set FormKey: file name} for the override check."""
    diffuse = {}
    for src in ('Skyrim', 'EnderalFS'):
        d = os.path.join(REF, 'base', src, 'TextureSets')
        for f in os.listdir(d):
            t = rd(os.path.join(d, f))
            fk = re.search(r'^FormKey: (\S+)', t, re.M).group(1)
            m = re.search(r'^\s*Diffuse: (.+)$', t, re.M)
            diffuse[fk] = file_name(m.group(1).strip()) if m else ''
    files, sets = {}, {}
    d = os.path.join(REF, 'base', 'Skyrim', 'LandscapeTextures')
    for f in os.listdir(d):
        t = rd(os.path.join(d, f))
        ts = re.search(r'^TextureSet: (\S+)', t, re.M)
        eid = re.search(r'^EditorID: (.+)$', t, re.M)
        if not ts or not diffuse.get(ts.group(1)):
            continue
        name = diffuse[ts.group(1)]
        files.setdefault(name, []).append(eid.group(1).strip() if eid else '?')
        sets[ts.group(1)] = name
    if not files:
        raise SystemExit('no landscape textures found in reference/base (serialize Skyrim.esm first)')
    return files, sets


def renamed_by_mods(sets):
    """texture sets of landscape textures that a serialized list mod gives another diffuse FILE NAME"""
    out = []
    root = os.path.join(REF, 'mods')
    if not os.path.isdir(root):
        return out
    for dirpath, _, names in os.walk(root):
        if os.path.basename(dirpath) != 'TextureSets':
            continue
        mod = os.path.relpath(dirpath, root).split(os.sep)[0]
        for f in names:
            t = rd(os.path.join(dirpath, f))
            fk = re.search(r'^FormKey: (\S+)', t, re.M)
            if not fk or fk.group(1) not in sets:
                continue
            m = re.search(r'^\s*Diffuse: (.+)$', t, re.M)
            new = file_name(m.group(1).strip()) if m else ''
            if new and new != sets[fk.group(1)]:
                out.append((mod, sets[fk.group(1)], new))
    return out


def build():
    files, sets = landscape_files()
    missing = sorted(set(MAPPING) - set(files))
    if missing:
        raise SystemExit(f'not an Enderal landscape texture file: {missing}')
    for mod, old, new in renamed_by_mods(sets):
        if old in MAPPING:
            print(f'WARNING: {mod} renames {old} -> {new}; add {new} to MAPPING too')

    kinds = {k: {} for k in KINDS}
    for name, choice in MAPPING.items():
        for kind, strength in choice.items():
            if kind not in kinds or not 0.0 <= strength <= 1.0:
                raise SystemExit(f'bad entry {name}: {kind} {strength}')
            default = default_strength(kind, name)
            if abs(strength - default) < 1e-6:
                raise SystemExit(f'{name}: {kind} {strength} is already the mod\'s default; drop it')
            kinds[kind][name] = ({'enabled': False, 'strength': 1.0} if strength == 0
                                 else {'enabled': True, 'strength': strength})
    root = {'version': 1}
    for k in KINDS:
        if kinds[k]:
            root[k] = {'textures': dict(sorted(kinds[k].items()))}

    # the result, per kind: what Enderal's ground kicks up with this file in place
    print(f'{len(files)} landscape texture files, {sum(len(v) for v in kinds.values())} entries written')
    for k in KINDS:
        eff = {}
        for name in files:
            s = default_strength(k, name)
            if name in kinds[k]:
                s = kinds[k][name]['strength'] if kinds[k][name]['enabled'] else 0.0
            if s > 0:
                eff[name] = s
        print(f'  {k}: ' + ', '.join(f'{n} {s:g}' + ('*' if n in kinds[k] else '') for n, s in sorted(eff.items())))
    return (json.dumps(root, indent=2) + '\n').encode('utf-8')


def main():
    mo2 = sys.argv[1] if len(sys.argv) > 1 else r'E:\Zenderal'
    data = build()
    json.loads(data)   # round trip
    targets = [os.path.join(PATCH, 'SKSE', 'Plugins', 'ResponsiveGrounds.json')]
    if os.path.isdir(os.path.join(mo2, 'mods')):
        targets.append(os.path.join(mo2, 'mods', MOD, 'SKSE', 'Plugins', 'ResponsiveGrounds.json'))
        meta = os.path.join(mo2, 'mods', MOD, 'meta.ini')
        os.makedirs(os.path.dirname(meta), exist_ok=True)
        if not os.path.exists(meta):
            with open(meta, 'wb') as f:
                f.write(META.encode('utf-8'))
    else:
        print(f'no MO2 mods folder under {mo2}: wrote the repo copy only')
    for t in targets:
        os.makedirs(os.path.dirname(t), exist_ok=True)
        with open(t, 'wb') as f:
            f.write(data)
        print('wrote', t)


if __name__ == '__main__':
    main()
