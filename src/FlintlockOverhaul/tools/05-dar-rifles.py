"""Zenderal - Flintlock Overhaul: DAR Rifles Standalone, used ONLY for its reload animations.
GENERATED - never hand-edit kid/ or DARRecipesOffESP/ConstructibleObjects/; re-run this instead.

1. kid/Zenderal - Flintlock Overhaul_KID.ini - DAR Rifles animates only weapons carrying its own
   keywords (_conditions.txt: IsEquippedRightHasKeyword("DAR Rifles.esp" | 0x800/0x801/0x802)), and Ordo
   Legionis' 14 muskets carry none, so the reload never played. KID gives all 14 the bolt-action
   keyword WeapTypeRifleBoltAction (0x800, the set DAR's own Charleville musket uses). KID reuses an
   existing keyword found by EditorID, so no master is needed. Shipped at the archive root: KID only
   reads Data/*_KID.ini.
2. Zenderal - DAR Rifles Recipes Off.esp - DAR Rifles.esp also adds 25 modern guns (AK-47, M16,
   blasters...) with 54 forge/grindstone recipes. Each is overridden with its CreatedObject /
   WorkbenchKeyword / count kept and one condition no player can meet (Smithing >= 1000; Enderal
   caps skills at 100), so it never appears at a bench. Items are left out on purpose: the
   originals reference Dawnguard.esm, an empty stub in Enderal, and a hidden recipe needs none.
   A separate plugin so the flintlock patch itself does not require DAR Rifles.

Run from the repo root: python -I src/FlintlockOverhaul/tools/05-dar-rifles.py
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
REF = os.path.join(ROOT, 'reference', 'mods')
HERE = os.path.join(ROOT, 'src', 'FlintlockOverhaul')
ORDO = 'OrdoLegionisMuskets.esp'
DAR = 'DAR Rifles.esp'
OFF = 'Zenderal - DAR Rifles Recipes Off.esp'

# ---- 1. KID
ids = sorted(int(re.search(r' - ([0-9A-F]{6})_', f).group(1), 16)
             for f in os.listdir(os.path.join(REF, 'OrdoEnderal', 'Weapons')))
if len(ids) != 14:
    sys.exit('expected 14 Ordo muskets, found %d' % len(ids))
os.makedirs(os.path.join(HERE, 'kid'), exist_ok=True)
lines = [
    '; Zenderal - Flintlock Overhaul: DAR Rifles reload animations for Ordo Legionis muskets.',
    '; DAR Rifles Standalone animates only weapons carrying its own keywords; Ordo\'s 14 muskets carry',
    '; none, so the reload never played. This gives all 14 the bolt-action keyword its own Charleville',
    '; musket uses. Requires DAR Rifles.esp enabled (the keyword lives there). Generated by',
    '; src/FlintlockOverhaul/tools/05-dar-rifles.py.',
    'Keyword = WeapTypeRifleBoltAction|Weapon|' + ','.join('0x%X~%s' % (i, ORDO) for i in ids),
]
with open(os.path.join(HERE, 'kid', 'Zenderal - Flintlock Overhaul_KID.ini'), 'w', encoding='utf-8', newline='\r\n') as f:
    f.write('\n'.join(lines) + '\n')

# ---- 2. recipe switch-off plugin
esp = os.path.join(HERE, 'DARRecipesOffESP')
cobj = os.path.join(esp, 'ConstructibleObjects')
os.makedirs(cobj, exist_ok=True)
for f in os.listdir(cobj):
    os.remove(os.path.join(cobj, f))
with open(os.path.join(esp, 'spriggit-meta.json'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('{\n  "PackageName": "Spriggit.Yaml.Skyrim",\n  "Version": "0.40.0",\n  "Release": "EnderalSE",\n'
            '  "ModKey": "%s"\n}\n' % OFF)
with open(os.path.join(esp, 'RecordData.yaml'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('SpriggitSource:\n  PackageName: Spriggit.Yaml.Skyrim\n  Version: 0.40\nModKey: %s\nGameRelease: EnderalSE\n'
            'ModHeader:\n  Flags:\n  - Small\n  Stats:\n    Version: 1.7\n  Author: Zenderal\n'
            '  Description: Hides DAR Rifles\' 54 modern-gun recipes; the mod is kept only for its reload animations.\n'
            '  MasterReferences:\n  - Master: Skyrim.esm\n    FileSize: 0\n  - Master: %s\n    FileSize: 0\n  INTV: 1\n'
            % (OFF, DAR))
COND = ('Conditions:\n- MutagenObjectType: ConditionFloat\n  CompareOperator: GreaterThanOrEqualTo\n  Data:\n'
        '    MutagenObjectType: GetActorValueConditionData\n    RunOnType: Reference\n'
        '    Reference: 000014:Skyrim.esm\n    ActorValue: Smithing\n  ComparisonValue: 1000\n')
n = 0
src = os.path.join(REF, 'DARRifles', 'ConstructibleObjects')
for f in sorted(os.listdir(src)):
    with open(os.path.join(src, f), encoding='utf-8') as fh:
        t = fh.read().replace('\r\n', '\n')
    if '\nConditions:' in t:
        sys.exit('%s already has conditions - merge instead' % f)
    keep = [l for l in t.split('\n') if re.match(r'^(FormKey|EditorID|CreatedObject|WorkbenchKeyword|CreatedObjectCount): ', l)]
    if len(keep) < 4 or not keep[0].endswith(':' + DAR):
        sys.exit('%s: unexpected shape %r' % (f, keep))
    out = '\n'.join(keep[:2]) + '\n' + COND + '\n'.join(keep[2:]) + '\n'
    with open(os.path.join(cobj, f), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(out)
    n += 1
if n != 54:
    sys.exit('expected 54 DAR Rifles recipes, wrote %d' % n)
print('KID: %d muskets; recipe overrides: %d' % (len(ids), n))
