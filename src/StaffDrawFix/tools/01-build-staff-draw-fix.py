"""Rebuild the `Zenderal - Staff Draw Fix` MO2 mod: an OAR submod that plays the vanilla staff draw in the
magic equip slots while a staff is in the right hand.

Smooth Magic Casting Animation 4.2 ships a legacy DAR folder `_CustomConditions/996` whose condition is
always true (`IsActorBase(Player) OR NOT IsActorBase(Player)`). Its `mrh_and_mlh_equip` / `mlh_equip`
therefore also replace the clips the behaviour graph activates right after `StaffRight_Equip`, and the
third-person staff draw (reach over the shoulder) never shows: the staff pops into the hand. Dynamic Random
Spell Idle's `Random Equip 1-3` replace the same clips with no staff exclusion. Both seen in OAR's animation
log 2026-10-13. Replacing them with the VANILLA magic clips did not help (see CLIPS).

The clips are Bethesda's, extracted from the user's own `Skyrim - Animations.bsa`, never committed.

Usage:  python 01-build-staff-draw-fix.py [<mods dir>]     (default E:/Zenderal/mods)
"""
import os, sys, json, hashlib, shutil
import importlib.util

_spec = importlib.util.spec_from_file_location(
    'restores', os.path.join(os.path.dirname(__file__), '..', '..', 'EnderalTextureRestores', 'tools',
                             '01-extract-enderal-textures.py'))
_restores = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_restores)
read_from_bsa = _restores.read_from_bsa

MOD = 'Zenderal - Staff Draw Fix'
OAR = ['meshes', 'actors', 'character', 'animations', 'OpenAnimationReplacer', 'Zenderal - Staff Draw Fix']
SUBMOD = 'Staff draw in magic equip slots'
OLD_SUBMODS = ['Vanilla magic equip with staff']  # v1, removed on rebuild
# published clip name -> vanilla clip it is extracted from. With a staff in the right hand the graph
# plays StaffRight_Equip AND the magic equip clips, and the full-upper-body MRh_and_MLh_Equip hides the
# staff draw even in its VANILLA form (verified in game 2026-10-13: v1 shipped the vanilla clips, the OAR
# log showed them winning, the staff still popped in). So the magic slots get the staff draw itself.
# Annotations: the vanilla magic equip clips carry none; staffright_equip carries only `weaponDraw`.
CLIPS = {
    'mrh_and_mlh_equip.hkx': 'staffright_equip.hkx',
    'mrh_equip.hkx': 'staffright_equip.hkx',
    'mlh_equip.hkx': 'mlh_equip.hkx',
}
PRIORITY = 8300000  # above Smooth Magic Casting's 996 and Dynamic Random Spell Idle's 8210000-8210025

MOD_CONFIG = {
    'name': 'Zenderal - Staff Draw Fix',
    'author': 'Zenderal',
    'description': 'Vanilla magic equip/unequip clips while a staff is in the right hand, so Smooth Magic '
                   'Casting no longer hides the third-person staff draw.',
}
SUBMOD_CONFIG = {
    'name': SUBMOD,
    'description': 'Right hand holds a staff: play the vanilla staff draw in the magic equip slots.',
    'priority': PRIORITY,
    'conditions': [
        {'condition': 'IsEquippedType', 'requiredVersion': '1.0.0.0', 'Type': {'value': 8.0}, 'Left hand': False},
    ],
}


def main():
    mods = sys.argv[1] if len(sys.argv) > 1 else 'E:/Zenderal/mods'
    bsa = os.path.join(os.path.dirname(mods.rstrip('/\\')), 'Stock Game', 'Data', 'Skyrim - Animations.bsa')
    mod_dir = os.path.join(mods, MOD, *OAR)
    sub_dir = os.path.join(mod_dir, SUBMOD)
    for old in OLD_SUBMODS + [SUBMOD]:
        if os.path.isdir(os.path.join(mod_dir, old)):
            shutil.rmtree(os.path.join(mod_dir, old))  # generated by this script only
    os.makedirs(sub_dir)
    with open(os.path.join(mod_dir, 'config.json'), 'w', encoding='utf-8') as fh:
        json.dump(MOD_CONFIG, fh, indent=4)
    with open(os.path.join(sub_dir, 'config.json'), 'w', encoding='utf-8') as fh:
        json.dump(SUBMOD_CONFIG, fh, indent=4)
    for clip, source in CLIPS.items():
        blob = read_from_bsa(bsa, 'meshes\\actors\\character\\animations\\' + source)
        with open(os.path.join(sub_dir, clip), 'wb') as fh:
            fh.write(blob)
        print(f'{len(blob):>8}  {hashlib.sha1(blob).hexdigest()[:12]}  {clip}  <- {source}')
    print(f'{len(CLIPS)} clips -> {sub_dir}')


if __name__ == '__main__':
    main()
