"""Vel'dun UI back in Futura: write a fontconfig.txt that maps the game's menu fonts to Futura Book BT.

Vel'dun UI 1.7 (2026-11-02) added an installer option for Oblivion Interaction Icons 3 beta ("4. Oblivion
Interaction Icons Patch" -> Patches/Vel'dun Oblivion Icons patch 3 beta). Its Interface/fontconfig.txt maps every
menu font ($StartMenuFont, $DialogueFont, $EverywhereFont, $EverywhereBoldFont, $EverywhereMediumFont) to "lato"
from Lato.swf, where Vel'dun's own config (Patches/Vel'dun UI 1.0.2) and its OII 1.x patch map them to
"Futura Book BT" from fonts_futura.swf. Installing that option on 2026-11-03 moved the whole UI from Futura to Lato.

This reads the winning Vel'dun fontconfig (the highest-priority enabled MO2 mod that ships Interface/fontconfig.txt,
other than ours) and writes a copy with only those five maps (plus $ListFont, which Vel'dun 1.0.2 maps and the beta
drops) pointed at Futura Book BT. Everything else stays as Vel'dun ships it: OII's Fonticon.swf + $Iconographia,
the Trattatello book font, the validNameChars line. It also guarantees the $Mage lines (Mage.swf + map) that the
beta config drops and Vel'dun's item card needs for talent words (mod-gotchas, 2026-11-05), so this mod carries
that fix too and survives a Vel'dun reinstall.

Writes, byte for byte apart from the edited lines (UTF-8, CRLF, as Vel'dun ships it):
  src/VeldunFuturaFont/Interface/fontconfig.txt            (committed, shipped by build/manifest.json)
  <MO2 mods>/Zenderal - Vel'dun Futura Font/Interface/fontconfig.txt  (+ meta.ini)

The MO2 mod must outrank every mod that ships Interface/fontconfig.txt (Veldun fomod files, Vel'dun UI Enderal
Default, Oblivion Interaction Icons). Rerun after a Vel'dun UI or OII update.

Usage: python -I src/VeldunFuturaFont/tools/01-build-fontconfig.py [<MO2 instance dir>]
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PATCH = os.path.dirname(HERE)
MOD = "Zenderal - Vel'dun Futura Font"
FUTURA = 'Futura Book BT'
FUTURA_LIB = r'fontlib "Interface\fonts_futura.swf"'
UI_FONTS = ['$StartMenuFont', '$DialogueFont', '$EverywhereFont', '$EverywhereBoldFont', '$EverywhereMediumFont']
REQUIRED_LIBS = [r'fontlib "Interface\Fonticon.swf"', r'fontlib "Interface\Mage.swf"']
REQUIRED_MAPS = {'$Iconographia': 'map "$Iconographia" = "Iconographia" Normal',
                 '$Mage': 'map "$Mage" = "Mage" Normal'}
META = ('[General]\r\ngameName=EnderalSE\r\nmodid=0\r\nversion=1.0.0\r\n'
        "comments=Generated by zenderal-patches src/VeldunFuturaFont/tools/01: Vel'dun UI's menu fonts back on "
        "Futura Book BT (its OII 3 beta patch maps them to Lato). Must outrank Veldun fomod files, "
        "Vel'dun UI Enderal Default and Oblivion Interaction Icons.\r\n")


def active_profile(root):
    for line in open(os.path.join(root, 'ModOrganizer.ini'), encoding='utf-8', errors='replace'):
        m = re.match(r'selected_profile=(?:@ByteArray\()?([^)\r\n]+)\)?', line)
        if m:
            return m.group(1)
    raise SystemExit('no selected_profile in ModOrganizer.ini')


def winning_source(root, profile):
    """Highest-priority enabled mod (modlist.txt top = highest) shipping Interface/fontconfig.txt, not ours."""
    lines = open(os.path.join(root, 'profiles', profile, 'modlist.txt'), encoding='utf-8').read().splitlines()
    for line in lines:
        if not line.startswith('+') or line[1:] == MOD:
            continue
        p = os.path.join(root, 'mods', line[1:], 'Interface', 'fontconfig.txt')
        if os.path.isfile(p):
            return line[1:], p
    raise SystemExit('no enabled mod ships Interface/fontconfig.txt')


def build(src_bytes):
    text = src_bytes.decode('utf-8')
    assert '\r\n' in text, 'expected CRLF'
    lines = text.split('\r\n')
    out, done = [], set()
    for line in lines:
        m = re.match(r'map "(\$[A-Za-z_]+)" = ', line)
        if m and m.group(1) in UI_FONTS:
            if m.group(1) in done:
                continue                               # a duplicate map would be ambiguous
            out.append(f'map "{m.group(1)}" = "{FUTURA}" Normal')
            done.add(m.group(1))
            continue
        if m and m.group(1) == '$ListFont':
            continue                                   # re-added below, once
        out.append(line)
    missing = [f for f in UI_FONTS if f not in done]
    if missing:
        raise SystemExit(f'source config has no map for {missing}')

    def insert_after(pred, new):
        idx = max(i for i, l in enumerate(out) if pred(l))
        out.insert(idx + 1, new)

    is_lib = lambda l: l.startswith('fontlib ')
    is_map = lambda l: l.startswith('map ')
    if FUTURA_LIB not in out:
        insert_after(is_lib, FUTURA_LIB)
    for lib in REQUIRED_LIBS:
        if lib not in out:
            insert_after(is_lib, lib)
    first_map = next(i for i, l in enumerate(out) if is_map(l))
    for name, mapline in REQUIRED_MAPS.items():
        if not any(l.startswith(f'map "{name}" = ') for l in out):
            out.insert(first_map, mapline)
    insert_after(lambda l: l.startswith('map "$Iconographia" = '), f'map "$ListFont" = "{FUTURA}" Normal')

    res = '\r\n'.join(out)
    # checks: every UI font and $ListFont exactly once and on Futura; Futura's library loaded; nothing maps to lato
    for name in UI_FONTS + ['$ListFont']:
        hits = [l for l in out if l.startswith(f'map "{name}" = ')]
        assert hits == [f'map "{name}" = "{FUTURA}" Normal'], (name, hits)
    assert out.count(FUTURA_LIB) == 1
    assert not any(re.search(r'= "lato"', l, re.I) for l in out)
    for name in REQUIRED_MAPS:
        assert sum(l.startswith(f'map "{name}" = ') for l in out) == 1, name
    return res.encode('utf-8')


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else r'E:\Zenderal'
    profile = active_profile(root)
    src_mod, src = winning_source(root, profile)
    data = build(open(src, 'rb').read())
    targets = [os.path.join(PATCH, 'Interface', 'fontconfig.txt'),
               os.path.join(root, 'mods', MOD, 'Interface', 'fontconfig.txt')]
    for t in targets:
        os.makedirs(os.path.dirname(t), exist_ok=True)
        with open(t, 'wb') as f:
            f.write(data)
    meta = os.path.join(root, 'mods', MOD, 'meta.ini')
    if not os.path.exists(meta):
        with open(meta, 'wb') as f:
            f.write(META.encode('utf-8'))
    print(f'source: {src_mod} ({profile})')
    for t in targets:
        print('wrote', t)
    print(data.decode('utf-8'))


if __name__ == '__main__':
    main()
