#!/usr/bin/env python3
"""Generate ZEN_SettingsApplier.psc (and its compile-only stubs) from data/settings.json.

The Zenderal list ships file-based settings (MCM Helper .ini, SKSE configs) in the
'Zenderal - Settings' MO2 mod. Legacy SkyUI MCMs keep their settings in the SAVE instead,
so they reset on every new character; this applier re-applies them once per save.

data/settings.json holds the captured values:
  globals     [{plugin, formid, edid, value}]          -> GlobalVariable.SetValue
  properties  [{plugin, formid, script, property, type, value}] -> (quest as Script).prop = v

Safety: every global is fetched with GetFormFromFile AND its EditorID compared
(PO3_SKSEFunctions.GetFormEditorID) before writing; every property write goes through a
cast that yields None if the mod is missing or its script was renamed. Anything that
does not match is logged and skipped - a changed or removed mod is never written blindly.

The quest waits 30 s before applying, because legacy MCMs initialise a few seconds after
a game starts and some reset their globals to their own defaults when they do.

Re-capture: decode a new save with tools/capture (ess.py / pex.py / bsa.py), update
data/settings.json, re-run this script, recompile (papyrus-compile), commit the .pex.
"""
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
DATA = json.load(open(os.path.join(ROOT, "data", "settings.json"), encoding="utf-8"))
SRC = os.path.join(ROOT, "Scripts", "source", "ZEN_SettingsApplier.psc")
STUBS = os.path.join(ROOT, "Scripts", "stubs")


def lit(t, v):
    if t == "Bool":
        return "True" if v else "False"
    if t == "Float":
        return repr(float(v))
    return str(int(v))


def esc(s):
    return s.replace('"', '\\"')


lines = [
    "Scriptname ZEN_SettingsApplier extends Quest",
    "{Applies the Zenderal list's save-based MCM settings once per save. GENERATED by",
    " src/SettingsApplier/tools/01-generate-applier.py from data/settings.json - do not edit.}",
    "",
    "Event OnInit()",
    "\tRegisterForSingleUpdate(30.0)",
    "EndEvent",
    "",
    "Event OnUpdate()",
    "\tInt applied = 0",
    "\tInt skipped = 0",
]
for g in DATA["globals"]:
    lines.append(f'\tIf SetG("{esc(g["plugin"])}", 0x{g["formid"]:X}, "{g["edid"]}", {float(g["value"])!r})')
    lines.append("\t\tapplied += 1")
    lines.append("\tElse")
    lines.append("\t\tskipped += 1")
    lines.append("\tEndIf")

by_script = {}
for p in DATA["properties"]:
    by_script.setdefault((p["plugin"], p["formid"], p["script"]), []).append(p)
for (plugin, formid, script), props in by_script.items():
    var = "q_" + script
    lines.append(f'\t{script} {var} = Game.GetFormFromFile(0x{formid:X}, "{esc(plugin)}") as {script}')
    lines.append(f"\tIf {var}")
    for p in props:
        lines.append(f'\t\t{var}.{p["property"]} = {lit(p["type"], p["value"])}')
        lines.append("\t\tapplied += 1")
    lines.append("\tElse")
    lines.append(f'\t\tDebug.Trace("[Zenderal Settings Applier] skipped {script} in {esc(plugin)}: not found or script changed")')
    lines.append(f"\t\tskipped += {len(props)}")
    lines.append("\tEndIf")

# Swift Potion Reborn: its settings are JContainers objects, not globals. Load the shipped exports
# exactly as its MCM "Load Settings" buttons do (_AP_ConfigSkyUIScript): assign PotionData, unregister
# hotkeys 1-12, assign HotkeyData, re-register each KeyCode. Requires its OnInit (modInstall) to have
# built HotkeyData first, so a zero HotkeyData means JContainers is not working: skip.
sp = DATA.get("swift_potion")
if sp:
    var, s = "q_" + sp["script"], sp["script"]
    lines += [
        f'\t{s} {var} = Game.GetFormFromFile(0x{sp["formid"]:X}, "{esc(sp["plugin"])}") as {s}',
        f'\tString spAutoPath = FindFile("{sp["dir"]}/{sp["auto"]}")',
        f'\tString spKeysPath = FindFile("{sp["dir"]}/{sp["hotkey"]}")',
        f"\tIf {var} && {var}.HotkeyData && spAutoPath != \"\" && spKeysPath != \"\"",
        "\t\tInt spAuto = JValue.readFromFile(spAutoPath)",
        "\t\tInt spKeys = JValue.readFromFile(spKeysPath)",
        "\t\tIf JValue.isMap(spAuto) && JValue.isMap(spKeys) && JMap.hasKey(spKeys, \"1\")",
        f"\t\t\t{var}.PotionData = spAuto",
        "\t\t\tInt k = 1",
        "\t\t\tWhile k < 13",
        f"\t\t\t\t{var}.SetHotkey(k as String, 0)",
        "\t\t\t\tk += 1",
        "\t\t\tEndWhile",
        f"\t\t\t{var}.HotkeyData = spKeys",
        "\t\t\tk = 1",
        "\t\t\tWhile k < 13",
        f"\t\t\t\t{var}.SetHotkey(k as String, JMap.getInt(JMap.getObj(spKeys, k as String), \"KeyCode\"))",
        "\t\t\t\tk += 1",
        "\t\t\tEndWhile",
        "\t\t\tapplied += 2",
        "\t\tElse",
        '\t\t\tDebug.Trace("[Zenderal Settings Applier] skipped Swift Potion: exported settings did not parse")',
        "\t\t\tskipped += 2",
        "\t\tEndIf",
        "\tElse",
        f'\t\tDebug.Trace("[Zenderal Settings Applier] skipped Swift Potion: {esc(sp["plugin"])} not loaded, not initialised, or settings files not found")',
        "\t\tskipped += 2",
        "\tEndIf",
    ]

# Enderal's call-horse key (_00E_HorseFlute_SC, a ReferenceAlias on NQ06_Freda) defaults to L, which
# Quick Light SE also uses, so one press both lit and called the horse. Move it while it is still the
# default. SetMountTeleportKey re-registers the key, which Enderal itself only does once the flute
# alias is filled (OnContainerChanged); before that, only set the property so the key stays inert.
hk = DATA.get("horse_key")
if hk:
    lines += [
        f'\tQuest qHorse = Game.GetFormFromFile(0x{hk["quest"]:X}, "{esc(hk["plugin"])}") as Quest',
        "\t_00E_HorseFlute_SC aHorse = None",
        "\tIf qHorse",
        f'\t\taHorse = qHorse.GetAlias({hk["alias"]}) as _00E_HorseFlute_SC',
        "\tEndIf",
        f'\tIf aHorse && aHorse.iMountHotkey == {hk["default"]}',
        "\t\tIf aHorse.GetReference()",
        f'\t\t\taHorse.SetMountTeleportKey({hk["key"]})',
        "\t\tElse",
        f'\t\t\taHorse.iMountHotkey = {hk["key"]}',
        "\t\tEndIf",
        "\t\tapplied += 1",
        "\tElse",
        '\t\tDebug.Trace("[Zenderal Settings Applier] skipped horse key: horse flute alias not found or key already changed")',
        "\t\tskipped += 1",
        "\tEndIf",
    ]

lines += [
    '\tDebug.Trace("[Zenderal Settings Applier] applied " + applied + ", skipped " + skipped)',
    "\tStop()",
    "EndEvent",
    "",
    "Bool Function SetG(String plugin, Int id, String edid, Float value)",
    "\tGlobalVariable g = Game.GetFormFromFile(id, plugin) as GlobalVariable",
    "\tIf !g",
    '\t\tDebug.Trace("[Zenderal Settings Applier] skipped " + edid + ": " + plugin + " not loaded")',
    "\t\tReturn False",
    "\tEndIf",
    "\tIf PO3_SKSEFunctions.GetFormEditorID(g) != edid",
    '\t\tDebug.Trace("[Zenderal Settings Applier] skipped " + edid + ": EditorID mismatch in " + plugin)',
    "\t\tReturn False",
    "\tEndIf",
    "\tg.SetValue(value)",
    "\tReturn True",
    "EndFunction",
    "",
]
if sp:
    # JContainers does not document what a relative path is relative to, so try the game root
    # ("Data/...") first, then the Data folder itself
    lines += [
        "String Function FindFile(String relPath)",
        '\tIf JContainers.fileExistsAtPath("Data/" + relPath)',
        '\t\tReturn "Data/" + relPath',
        "\tElseIf JContainers.fileExistsAtPath(relPath)",
        "\t\tReturn relPath",
        "\tEndIf",
        '\tReturn ""',
        "EndFunction",
        "",
    ]
os.makedirs(os.path.dirname(SRC), exist_ok=True)
open(SRC, "w", encoding="utf-8", newline="\r\n").write("\n".join(lines))

# compile-only stubs: declare just the properties written; NEVER shipped (real scripts run in game)
os.makedirs(STUBS, exist_ok=True)
for (plugin, formid, script), props in by_script.items():
    stub = [f"Scriptname {script} extends Quest Hidden",
            f"{{COMPILE-ONLY STUB of {plugin}'s {script}. Not shipped.}}"]
    for p in props:
        stub.append(f'{p["type"]} Property {p["property"]} Auto')
    open(os.path.join(STUBS, script + ".psc"), "w", encoding="utf-8", newline="\r\n").write("\n".join(stub) + "\n")
if sp:
    stub = [f'Scriptname {sp["script"]} extends Quest Hidden',
            f'{{COMPILE-ONLY STUB of {sp["plugin"]}\'s {sp["script"]}. Not shipped.}}',
            "Int Property PotionData Auto",
            "Int Property HotkeyData Auto",
            "Function SetHotkey(String iHotkey, Int newKeyCode)",
            "EndFunction"]
    open(os.path.join(STUBS, sp["script"] + ".psc"), "w", encoding="utf-8", newline="\r\n").write("\n".join(stub) + "\n")
print(f"wrote {SRC}: {len(DATA['globals'])} globals, {len(DATA['properties'])} properties; {len(by_script)} stubs")
